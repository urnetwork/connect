package fingerprint

// golden.go -- the committed golden fixtures and their provenance, and the
// impl-independent generator for the synthetic golden.
//
// a golden is one named Chrome version's ClientHello handshake message, stored
// as raw bytes under testdata/fingerprints with the version in the filename
// (e.g. chrome-133-clienthello-synthetic.bin). Layer A compares connect's
// emitted hello against it; Layer B (the Docker runner) regenerates it from
// real Chrome and stamps the real version.
//
// the golden shipped here is SYNTHETIC: it is the uTLS v1.8.2 HelloChrome_133
// profile that connect parrots, generated by this package, not a capture of
// real Chrome. it pins "connect still matches the uTLS Chrome_133 reference".
// the owner replaces it with a real-Chrome capture (Layer B) to upgrade the
// gate to "connect still matches real Chrome"; the refresh runbook is in
// README.md.

import (
	"embed"
	"fmt"
	"net"
	"os"
	"path/filepath"

	utls "github.com/refraction-networking/utls"
)

// the committed goldens, embedded so any package (connect's own dialers
// included) can load them without a path relative to this directory.
//
//go:embed testdata/fingerprints/*.bin
var goldenFiles embed.FS

// GoldenRef names a committed golden and its provenance. describe() renders the
// provenance into a drift message so a failure says which Chrome version to
// refresh.
type GoldenRef struct {
	// the embedded path of the golden's raw ClientHello bytes.
	Path string
	// the Chrome version the golden represents.
	ChromeVersion string
	// when the golden was captured or generated (ISO date).
	CaptureDate string
	// how the golden was produced, for the drift message and the reviewer.
	Source string
	// whether the golden is synthetic (uTLS, not real Chrome).
	Synthetic bool
}

func (self GoldenRef) describe() string {
	kind := "real-Chrome golden"
	if self.Synthetic {
		kind = "synthetic golden"
	}
	return fmt.Sprintf("the chrome-%s %s (%s, captured %s)", self.ChromeVersion, kind, self.Source, self.CaptureDate)
}

