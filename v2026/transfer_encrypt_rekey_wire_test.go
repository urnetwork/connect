// Delivers the server controller's serialized response through the contract
// manager's ordinary out-of-band callback. It takes requests and lends the reply.
type tlsWireContractOob struct {
	reply       *protocol.Frame
	destination Id
	role        protocol.SequenceRole
	requests    atomic.Int64
}

func (self *tlsWireContractOob) SendControl(frames []*protocol.Frame, callback OobResultFunction) {
	var results []*protocol.Frame
	var resultErr error
	defer func() {
		for _, frame := range frames {
			MessagePoolReturn(frame.MessageBytes)
		}
	}()
	if callback != nil {
		defer func() { callback(results, resultErr) }()
	}
	for _, frame := range frames {
		if frame.MessageType != protocol.MessageType_TransferCreateContract {
			continue
		}
		request := &protocol.CreateContract{}
		if resultErr = proto.Unmarshal(frame.MessageBytes, request); resultErr != nil {
			return
		}
		if !bytes.Equal(request.DestinationId, self.destination.Bytes()) || request.GetSenderRole() != self.role ||
			request.GetForceStream() || request.GetCompanion() || request.GetStreamVersion() != uint32(DefaultStreamVersion) {
			resultErr = fmt.Errorf("unexpected create contract request for role %s and stream version %d", request.GetSenderRole(), request.GetStreamVersion())
			return
		}
		self.requests.Add(1)
		results = append(results, self.reply)
	}
}

// The fixture contains the complete CreateContract frames generated by the
// controller test. Its signed expiration is checked against the test clock.
func readTlsWireContracts(t *testing.T) ([3]*protocol.Frame, [3]*protocol.StoredContract) {
	t.Helper()
	path := os.Getenv("URNETWORK_TLS_CONTRACT_FIXTURE_IN")
	if path == "" {
		path = "testdata/tls_session_contracts.json"
	}
	encoded, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var wire struct{ Initial, Rotation, Reply []byte }
	if err := json.Unmarshal(encoded, &wire); err != nil {
		t.Fatal(err)
	}
	var frames [3]*protocol.Frame
	var contracts [3]*protocol.StoredContract
	for index, payload := range [3][]byte{wire.Initial, wire.Rotation, wire.Reply} {
		frame := &protocol.Frame{}
		if err := proto.Unmarshal(payload, frame); err != nil {
			t.Fatal(err)
		}
		result := &protocol.CreateContractResult{}
		if frame.MessageType != protocol.MessageType_TransferCreateContractResult {
			t.Fatalf("response %d has frame type %s", index, frame.MessageType)
		}
		if err := proto.Unmarshal(frame.MessageBytes, result); err != nil {
			t.Fatal(err)
		}
		if result.Error != nil || result.Contract == nil || result.CreateContract == nil ||
			result.Contract.ProvideMode != protocol.ProvideMode_Network {
			t.Fatalf("response %d is missing an issued Network contract", index)
		}
		stored := &protocol.StoredContract{}
		if err := proto.Unmarshal(result.Contract.StoredContractBytes, stored); err != nil {
			t.Fatal(err)
		}
		echo := result.CreateContract
		if !bytes.Equal(stored.DestinationId, echo.DestinationId) || echo.GetStreamVersion() != uint32(DefaultStreamVersion) ||
			echo.ForceStream == nil || echo.GetForceStream() || echo.GetCompanion() {
			t.Fatalf("response %d lacks the issued request for the regular lane", index)
		}
		frames[index], contracts[index] = frame, stored
	}
	return frames, contracts
}

// Observe both the refusal from the real writer and the exact no-ACK route try.
type tlsWireWriteLog struct {
	Logger
	certRefusals atomic.Int64
	signal       func()
}

func (self *tlsWireWriteLog) Errorf(format string, _ ...any) {
	if strings.Contains(format, "sequence TLS cert verification failed") {
		self.certRefusals.Add(1)
		self.signal()
	}
}

func TestRequiredSessionCommittedCertificateRekey(t *testing.T) {
	testRequiredSessionCertificateRekey(t, true)
}

func TestRequiredSessionUncommittedCertificateRekey(t *testing.T) {
	testRequiredSessionCertificateRekey(t, false)
}

func testRequiredSessionCertificateRekey(t *testing.T, committed bool) {
	t.Helper()
	frames, contracts := readTlsWireContracts(t)
	ownedTestWireSynctest(t, func(t *testing.T) {
		ids := [2]Id{RequireIdFromBytes(contracts[0].SourceId), RequireIdFromBytes(contracts[0].DestinationId)}
		for i, stored := range contracts {
			side := 0
			if i == 2 {
				side = 1
			}
			if !bytes.Equal(stored.SourceId, ids[side].Bytes()) || !bytes.Equal(stored.DestinationId, ids[1-side].Bytes()) ||
				!time.Now().Before(time.UnixMilli(stored.GetExpirationTimeUnixMilli())) {
				t.Fatalf("contract %d has an unexpected endpoint or expired signed deadline", i)
			}
		}
		first, rollover := contracts[0].GetProvideTlsCertificate(), contracts[1].GetProvideTlsCertificate()
		if len(first) != 1 || len(rollover) != 2 || !bytes.Equal(first[0], rollover[0]) || bytes.Equal(rollover[0], rollover[1]) {
			t.Fatal("signed fixture does not commit the expected original and replacement leaves")
		}
		serverConfig, err := DefaultSequenceServerTlsConfig()
		if err != nil {
			t.Fatal(err)
		}
		replacementConfig := serverConfig.Clone()
		for index, config := range []*tls.Config{serverConfig, replacementConfig} {
			leaf, _ := pem.Decode(rollover[index])
			if leaf == nil {
				t.Fatal("invalid fixture leaf")
			}
			key := ed25519.NewKeyFromSeed(bytes.Repeat([]byte{byte(71 + index)}, ed25519.SeedSize))
			config.Certificates = []tls.Certificate{{Certificate: [][]byte{leaf.Bytes}, PrivateKey: key}}
		}
		var rotate atomic.Bool
		serverConfig.GetConfigForClient = func(*tls.ClientHelloInfo) (*tls.Config, error) {
			if rotate.Load() {
				return replacementConfig, nil
			}
			return nil, nil
		}

		contractIndex := 0
		if committed {
			contractIndex = 1
		}
		from := &tlsWireContractOob{reply: frames[contractIndex], destination: ids[1], role: protocol.SequenceRole_SequenceRoleClient}
		to := &tlsWireContractOob{reply: frames[2], destination: ids[0], role: protocol.SequenceRole_SequenceRoleServer}
		log := &tlsWireWriteLog{Logger: NewNoopLogger()}
		fastPath := make(chan error, 2)
		firstWrite := make(chan error, 2)
		p := newTlsWirePair(t, ids, [2]OutOfBandControl{from, to}, func(side int, settings *ClientSettings) {
			settings.ContractManagerSettings.NetworkEventTimeEnableContracts = time.Unix(1, 0)
			settings.ContractManagerSettings.NetworkEventTimeChangeHmac = time.Unix(1, 0)
			if side == 1 {
				settings.EncryptionSettings.ServerTlsConfig = serverConfig
			} else {
				settings.Log = log
				settings.SendBufferSettings.SendPackLifecycleObserver = func(ev SendPackLifecycleObservation) {
					if ev.Phase == SendPackLifecyclePhaseFirstRouteWrite && ev.AckRequired &&
						ev.DestinationId == ids[1] && ev.MessageType == protocol.MessageType_TestSimpleMessage {
						firstWrite <- ev.Err
					}
				}
				settings.SendBufferSettings.afterNoAckFastPathForTest = func(id sendSequenceId, attempted, written bool, _ time.Duration) {
					if id.Destination != ids[1] {
						return
					}
					var err error
					if !attempted || written != committed {
						err = fmt.Errorf("no-ACK fast path attempted=%t written=%t for committed=%t", attempted, written, committed)
					}
					fastPath <- err
				}
			}
		})
		defer p.close()
		log.signal = p.signal
		for side, client := range p.clients {
			client.ContractManager().LoadProvideSecretKeys(map[protocol.ProvideMode][]byte{
				protocol.ProvideMode_Network: bytes.Repeat([]byte{byte(81 + side)}, 32),
			})
			client.ContractManager().SetProvideModes(map[protocol.ProvideMode]bool{protocol.ProvideMode_Network: true})
		}
		a, b := p.clients[0], p.clients[1]
		sender := a.EncryptionSessionManager().AcquireForSend(ids[1], sequenceTlsRoleClient, false, false, false)
		defer sender.Release()
		var receiver *peerEncryptionSession
		p.await("initial TLS with the issued contract", func() bool {
			receiver = b.EncryptionSessionManager().Lookup(ids[0], sequenceTlsRoleServer, false)
			return sender.Cipher() != nil && receiver != nil && receiver.Cipher() != nil
		})
		old := sender.currentEpoch()
		oldId := sender.epochIdOf(old)
		originalResponder := receiver.currentEpoch()
		if verified, absent := sender.CertVerificationState(); verified || absent || from.requests.Load() == 0 || to.requests.Load() == 0 {
			t.Fatalf("initial TLS is missing an unchecked server-issued commitment, verified=%t absent=%t requests=%d/%d", verified, absent, from.requests.Load(), to.requests.Load())
		}

		rotate.Store(true)
		var heldProof []byte
		var replacement *tlsHandshakeEpoch
		type applicationWrite struct {
			label string
			epoch *tlsHandshakeEpoch
		}
		var applicationWrites []applicationWrite
		writes := func() []applicationWrite {
			p.wireLock.Lock()
			defer p.wireLock.Unlock()
			return slices.Clone(applicationWrites)
		}
		dropFirst := true
		p.setWirePolicy(func(side int, wire []byte) bool {
			if side == 1 {
				ec := tlsWireControl(wire, protocol.EncryptedControlType_EncryptedControlIdentityProof)
				if ec != nil && !bytes.Equal(ec.EpochId, oldId.Bytes()) && heldProof == nil {
					heldProof = bytes.Clone(wire)
					return false
				}
				return true
			}
			pack, record := tlsWireContents(wire)
			var owner *tlsHandshakeEpoch
			if len(record) != 0 {
				for _, epoch := range []*tlsHandshakeEpoch{old, replacement} {
					if epoch == nil || epoch.derivedTlsCipher == nil {
						continue
					}
					opened, err := epoch.derivedTlsCipher.Open(record)
					if err == nil {
						if owner != nil {
							t.Error("record opened with both generations")
						}
						owner = epoch
						pack, _ = tlsWireContents(opened)
						MessagePoolReturn(opened)
					}
				}
				if owner == nil {
					t.Error("sealed route write opened with neither TLS epoch")
				}
			}
			for _, label := range tlsWireApplicationLabels(t, pack.GetFrames()) {
				applicationWrites = append(applicationWrites, applicationWrite{label: label, epoch: owner})
				if label == "held write" && dropFirst {
					dropFirst = false
					return false
				}
			}
			return true
		})
		rekey := a.EncryptionSessionManager().AcquireForSend(ids[1], sequenceTlsRoleClient, false, false, false)
		defer rekey.Release()
		p.await("replacement TLS with the peer's proof held", func() bool {
			receiver.stateLock.Lock()
			defer receiver.stateLock.Unlock()
			return heldProof != nil && receiver.establishedEpoch != nil && receiver.establishedEpoch != originalResponder &&
				receiver.establishedEpoch == receiver.epoch
		})
		p.wireLock.Lock()
		sender.stateLock.Lock()
		replacement = sender.epoch
		pending := replacement != nil && replacement != old && replacement.derivedTlsCipher != nil && sender.establishedEpoch == old
		sender.stateLock.Unlock()
		p.wireLock.Unlock()
		if rekey != sender || !pending {
			t.Fatal("replacement TLS must finish while the original cipher still serves")
		}
		for index, epoch := range []*tlsHandshakeEpoch{old, replacement} {
			peers := epoch.tlsConn.ConnectionState().PeerCertificates
			leaf, _ := pem.Decode(rollover[index])
			if len(peers) != 1 || !bytes.Equal(peers[0].Raw, leaf.Bytes) {
				t.Fatalf("TLS handshake %d presented the wrong leaf", index)
			}
		}
		reachedVerification, resumeWrite := make(chan struct{}), make(chan struct{})
		sender.beforeCertVerifiedMarkForTest = func() {
			select {
			case <-reachedVerification:
				return
			default:
				close(reachedVerification)
			}
			select {
			case <-resumeWrite:
			case <-p.ctx.Done():
			}
		}
		receipt := p.send("held write")
		synctest.Wait()
		select {
		case <-reachedVerification:
		default:
			t.Fatal("application writer skipped the committed certificate check")
		}
		p.in[0] <- MessagePoolCopy(heldProof)
		synctest.Wait()
		replacementId := sender.epochIdOf(replacement)
		receiver.stateLock.Lock()
		responderEpoch := receiver.establishedEpoch
		agreed := responderEpoch != nil && responderEpoch == receiver.epoch && responderEpoch.epochId == replacementId
		receiver.stateLock.Unlock()
		if !agreed || sender.Cipher() != replacement.derivedTlsCipher {
			t.Fatal("replacement did not authenticate while the application writer was paused")
		}
		close(resumeWrite)
		if err := p.waitResult("paused application write", firstWrite); err != nil {
			t.Fatalf("original epoch failed to write after rekey: %v", err)
		}
		if !slices.Equal(writes(), []applicationWrite{{label: "held write", epoch: old}}) {
			t.Fatal("the held write did not seal with the generation it verified")
		}
		if committed {
			if err := p.waitResult("acknowledged retry under the replacement certificate", receipt); err != nil {
				t.Fatalf("reliable retry failed: %v", err)
			}
			if !slices.Equal(writes(), []applicationWrite{
				{label: "held write", epoch: old}, {label: "held write", epoch: replacement},
			}) {
				t.Fatal("reliable retry did not seal with the verified replacement")
			}
			p.send("no ack", NoAck())
			if err := p.waitResult("no-ACK fast path", fastPath); err != nil {
				t.Fatal(err)
			}
			p.await("no-ACK delivery", func() bool { return len(p.deliveries(1)) >= 2 })
			recorded := writes()
			if len(recorded) != 3 || recorded[2] != (applicationWrite{label: "no ack", epoch: replacement}) ||
				!slices.Equal(p.deliveries(1), []string{"held write", "no ack"}) {
				t.Fatal("replacement did not deliver through the no-ACK fast path")
			}
		} else {
			p.await("reliable retry certificate refusal", func() bool { return log.certRefusals.Load() > 0 || len(applicationWrites) > 1 })
			if log.certRefusals.Load() != 1 || len(writes()) != 1 || len(p.deliveries(1)) != 0 {
				t.Fatalf("uncommitted replacement retry, writes=%d refusals=%d delivered=%v",
					len(writes()), log.certRefusals.Load(), p.deliveries(1))
			}
			noAck := p.send("no ack", NoAck())
			if err := p.waitResult("no-ACK fast path", fastPath); err != nil {
				t.Fatal(err)
			}
			if err := p.waitResult("no-ACK result", noAck); err == nil || !strings.Contains(err.Error(), "cert verification failed") ||
				len(writes()) != 1 || len(p.deliveries(1)) != 0 {
				t.Fatalf("no-ACK attempt with uncommitted certificate, result=%v application=%d delivered=%v",
					err, len(writes()), p.deliveries(1))
			}
			p.send("new reliable write")
			if err := p.waitResult("certificate refusal of new reliable write", firstWrite); err == nil || !strings.Contains(err.Error(), "cert verification failed") ||
				len(writes()) != 1 || len(p.deliveries(1)) != 0 {
				t.Fatalf("new reliable write with uncommitted certificate, result=%v application=%d delivered=%v", err, len(writes()), p.deliveries(1))
			}
		}
		if verified, absent := sender.CertVerificationState(); verified != committed || absent {
			t.Fatalf("replacement certificate decision, verified=%t absent=%t", verified, absent)
		}
	})
}
