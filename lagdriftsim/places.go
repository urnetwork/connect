package lagdriftsim

// The study's places: where extenders are, where visitors are, and where an
// address that claims a country puts its holder.
//
// lag.dev's e2e stack (lag.dev/e2e/stack/dots.json) holds 12 real cities, all
// around one visitor in Austin: too few for E2's bands from anywhere else. So
// the extender pool is a plausible global fleet instead, weighted toward
// Europe and North America as the network's extenders are: datacenter cities
// with one or more extenders each, 182 in all. dots.json's 12 cities are among
// them. GeoLite2 puts a datacenter address at its city's point, so extenders in
// one city share a place.

import (
	"github.com/urnetwork/connect/lagdrift"
)

// A city.
type place struct {
	name string
	// GeoLite2's country code, lower case
	code string
	at   lagdrift.Point
}

func newPlace(name string, code string, lat float64, lon float64) place {
	return place{
		name: name,
		code: code,
		at:   lagdrift.Point{Lat: lat, Lon: lon},
	}
}

// A datacenter city and how many extenders it has.
type extenderSite struct {
	place
	count int
}

func site(name string, code string, lat float64, lon float64, count int) extenderSite {
	return extenderSite{place: newPlace(name, code, lat, lon), count: count}
}

