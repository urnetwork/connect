// A one-shot channel barrier, installed before the real sender starts.
type evictionFeedbackGate struct {
	armed       atomic.Bool
	entered     chan struct{}
	released    chan struct{}
	releaseOnce sync.Once
}

func newEvictionFeedbackGate() *evictionFeedbackGate {
	return &evictionFeedbackGate{entered: make(chan struct{}), released: make(chan struct{})}
}

func (self *evictionFeedbackGate) park() {
	if self.armed.CompareAndSwap(true, false) {
		close(self.entered)
		<-self.released
	}
}

func (self *evictionFeedbackGate) release() {
	self.releaseOnce.Do(func() { close(self.released) })
}

func (self *evictionFeedbackGate) requireEntered(t *testing.T) {
	t.Helper()
	synctest.Wait()
	select {
	case <-self.entered:
	default:
		t.Fatal("real sender did not reach the armed feedback-cut barrier")
	}
}

// Both ACKs are generated by the actual receiving client. The notice repeats
// a real eviction using the normal metadata producer, exactly as the existing
// released-carrier wake regression does. It names the already-retired head0.
type evictionFeedbackFixture struct {
	wire          *windowRoundFixture
	afterSnapshot *evictionFeedbackGate
	afterInitial  *evictionFeedbackGate
	ownerExited   chan struct{}
	ownerExitOnce sync.Once
	sequence      *SendSequence
	receiver      *ReceiveSequence
	gap           *windowRoundFrame
	middle        *windowRoundFrame
	victim        *windowRoundFrame
	sack          *windowRoundFrame
	notice        *windowRoundFrame
}

func newEvictionFeedbackFixture(t *testing.T, holdBeforeSnapshot bool, configure ...func(*SendBufferSettings)) *evictionFeedbackFixture {
	t.Helper()
	f := &evictionFeedbackFixture{
		afterSnapshot: newEvictionFeedbackGate(),
		afterInitial:  newEvictionFeedbackGate(),
		ownerExited:   make(chan struct{}),
	}
	f.wire = newWindowRoundFixture(t, func(settings *SendBufferSettings) {
		settings.afterApplyAckSnapshotForTest = func(sendSequenceId) {
			f.afterSnapshot.park()
		}
		settings.afterInitialWriteQueuedForTest = func(_ sendSequenceId, number uint64) {
			if number == 3 {
				f.afterInitial.park()
			}
		}
		settings.afterRunSendSequenceForTest = func(sendSequenceId) {
			f.ownerExitOnce.Do(func() { close(f.ownerExited) })
		}
		for _, change := range configure {
			change(settings)
		}
	}, func(settings *ReceiveBufferSettings) {
		settings.ReceiveQueueMaxByteCount = 2 * 1024
		settings.ReceiveHoldPolicy = ReceiveHoldEvict
		settings.EvictionNotice = true
	})
	// LIFO cleanup releases every test gate before the fixture cancels/joins.
	t.Cleanup(func() {
		f.afterSnapshot.release()
		f.afterInitial.release()
	})
	seed := f.wire.write(1024)
	f.wire.forward(f.wire.receive(seed), f.wire.senderIn)
	f.gap, f.middle = f.wire.write(1024), f.wire.write(1024)
	if holdBeforeSnapshot {
		f.afterInitial.armed.Store(true)
	}
	f.victim = f.wire.write(1024)
	if holdBeforeSnapshot {
		f.afterInitial.requireEntered(t)
	}
	f.sequence, f.receiver = f.wire.sequence(), f.wire.receiveSequence()
	// The receiver does not exist until the seed round, so fetch it above only
	// after the actual public seed exchange. Victim remains behind gap1.
	f.sack = f.wire.receive(f.victim)
	if f.sack.ack == nil || !f.sack.ack.Selective ||
		!bytes.Equal(f.sack.ack.MessageId, f.victim.pack.MessageId) ||
		len(f.sack.ack.EvictedSequenceNumbers) != 0 {
		t.Fatal("actual victim admission did not produce its exact ordinary SACK")
	}
	if _, retained := f.sequence.retainedAckSequenceNumber(RequireIdFromBytes(seed.pack.MessageId)); retained {
		t.Fatal("head0 ACK carrier unexpectedly retains a source owner")
	}
	f.wire.forward(f.middle, f.wire.receiverIn)
	actual := f.wire.takeAcknowledgements()
	notices := 0
	for _, ack := range actual {
		for _, number := range ack.ack.EvictedSequenceNumbers {
			if number != f.victim.pack.SequenceNumber {
				t.Fatal("actual receiver eviction named another source owner")
			}
			notices++
		}
	}
	if notices != 1 || f.wire.receiver.ReceiveStats().ReceiveQueueEvictionCount != 1 ||
		f.receiver.receiveQueue.GetBySequenceNumber(f.victim.pack.SequenceNumber) != nil {
		t.Fatal("real earlier admission did not evict the exact victim")
	}
	f.receiver.noteEviction(f.victim.pack.SequenceNumber)
	acks := f.wire.takeAcknowledgements()
	if len(acks) != 1 || acks[0].ack.Selective ||
		!bytes.Equal(acks[0].ack.MessageId, seed.pack.MessageId) ||
		len(acks[0].ack.EvictedSequenceNumbers) != 1 ||
		acks[0].ack.EvictedSequenceNumbers[0] != f.victim.pack.SequenceNumber {
		t.Fatal("normal ACK worker did not encode the actual withdrawal on retired head0")
	}
	f.notice = acks[0]
	return f
}

// Stops the owning Run after it has already consumed an empty ACK snapshot.
func (self *evictionFeedbackFixture) stopAfterSnapshot(t *testing.T) {
	t.Helper()
	self.afterSnapshot.armed.Store(true)
	self.sequence.ackWindow.Wake()
	self.afterSnapshot.requireEntered(t)
}

// Common read-only test state, selected from actual OLD vector or FIX owner
// markers. Nonapplicable phase fields are zero on OLD, never mirrored in prod.
type pendingEvictionTestState struct {
	numbers      []uint64
	pending      uint8
	inFlight     uint8
	detached     bool
	backingBytes ByteCount
}

// Inspects actual pending state through the arm's synchronized accessor.
func (self *evictionFeedbackFixture) pendingCount() int {
	return len(pendingEvictionStateForTest(self.sequence).numbers)
}

// Records the prompt-repair result before any backstop event. A failing arm
// receives one explicit second real notice only to complete exact pool/owner
// reconciliation; that cleanup rescue never satisfies the prompt assertion.
func (self *evictionFeedbackFixture) requireRepairAndFinish(t *testing.T, label string) {
	t.Helper()
	synctest.Wait()
	prompt := self.wire.sender.SendRecoveryStats().SendEvictionResendCount == 1 &&
		len(self.wire.senderOut) == 1 && self.pendingCount() == 0
	if !prompt {
		t.Errorf("%s: genuine pending SACK outlived its accepted eviction; no prompt exact repair", label)
	}
	self.finishRepairAndReconcile(t, label, prompt)
}

// Completes reconciliation after recording, never masking, the prompt result.
func (self *evictionFeedbackFixture) finishRepairAndReconcile(t *testing.T, label string, prompt bool) {
	t.Helper()
	at := time.Now()
	if self.wire.ackedCount != 1 || self.wire.deliveredCount != 1 {
		t.Fatal("metadata or selective receipt fabricated terminal delivery credit")
	}
	if !prompt {
		// The owner has now applied the SACK. A fresh notice is a deliberate
		// cleanup backstop, not an allowed prerequisite for the tested repair.
		self.receiver.noteEviction(self.victim.pack.SequenceNumber)
		for _, ack := range self.wire.takeAcknowledgements() {
			self.wire.forward(ack, self.wire.senderIn)
		}
	}
	resent := self.wire.take(self.wire.senderOut)
	if resent.pack == nil || !bytes.Equal(resent.pack.SequenceId, self.victim.pack.SequenceId) ||
		!bytes.Equal(resent.pack.MessageId, self.victim.pack.MessageId) ||
		resent.pack.SequenceNumber != self.victim.pack.SequenceNumber ||
		!reflect.DeepEqual(resent.pack.Frames, self.victim.pack.Frames) ||
		self.wire.sender.SendRecoveryStats().SendEvictionResendCount != 1 ||
		self.pendingCount() != 0 || time.Now() != at {
		t.Fatal("eviction repair changed exact custody, repeated dispatch, or advanced a timer")
	}
	self.wire.forward(self.wire.receive(self.gap), self.wire.senderIn)
	self.wire.forward(self.wire.receive(resent), self.wire.senderIn)
	if self.wire.deliveredCount != 4 || self.wire.ackedCount != 4 ||
		self.sequence.resendQueue.Len() != 0 {
		t.Fatal("repair did not reconcile every original delivery/ACK/payload owner")
	}
	t.Logf("%s: prompt=%t exact_recovery=true terminal_owners=4 timer_advance=0", label, prompt)
}

// Intended source-supported OLD-red/FIX-green discriminator, not yet executed.
func TestEvictionFeedbackPendingSackCannotOutliveWithdrawal(t *testing.T) {
	assertMessagePoolOwnership(t)
	synctest.Test(t, func(t *testing.T) {
		f := newEvictionFeedbackFixture(t, false)
		f.stopAfterSnapshot(t)
		at := time.Now()
		f.wire.forward(f.sack, f.wire.senderIn)
		f.wire.forward(f.notice, f.wire.senderIn)
		if !f.sequence.ackWindow.Pending() || f.pendingCount() != 1 || time.Now() != at {
			t.Fatal("split-cut setup did not publish both genuine feedback records while Run was held")
		}
		f.afterSnapshot.release()
		f.requireRepairAndFinish(t, "split ACK snapshot")
	})
}

// Both records precede the next real Run snapshot; OLD should already pass.
func TestEvictionFeedbackBeforeSnapshotRepairsExactOwner(t *testing.T) {
	assertMessagePoolOwnership(t)
	synctest.Test(t, func(t *testing.T) {
		f := newEvictionFeedbackFixture(t, true)
		f.wire.forward(f.sack, f.wire.senderIn)
		f.wire.forward(f.notice, f.wire.senderIn)
		if !f.sequence.ackWindow.Pending() || f.pendingCount() != 1 {
			t.Fatal("pre-snapshot setup did not retain both genuine records")
		}
		f.afterInitial.release()
		f.requireRepairAndFinish(t, "before ACK snapshot")
	})
}

// A previously applied lease also remains repairable on an old ACK carrier.
func TestEvictionFeedbackAppliedSackRepairsExactOwner(t *testing.T) {
	assertMessagePoolOwnership(t)
	synctest.Test(t, func(t *testing.T) {
		f := newEvictionFeedbackFixture(t, false)
		f.wire.forward(f.sack, f.wire.senderIn)
		f.stopAfterSnapshot(t)
		item := f.sequence.resendQueue.GetBySequenceNumber(f.victim.pack.SequenceNumber)
		if item == nil || !item.selectiveAcked {
			t.Fatal("normal-order control did not apply the victim SACK before withdrawal")
		}
		f.wire.forward(f.notice, f.wire.senderIn)
		f.afterSnapshot.release()
		f.requireRepairAndFinish(t, "already-applied SACK")
	})
}

// A bounded exact-owner successor must repair the independently reproduced
// vector growth, not merely keep the earlier feedback ordering tests green.
func TestEvictionFeedbackDuplicateNoticesAreOwnerBounded(t *testing.T) {
	assertMessagePoolOwnership(t)
	synctest.Test(t, func(t *testing.T) {
		f := newEvictionFeedbackFixture(t, false)
		f.wire.forward(f.sack, f.wire.senderIn)
		f.stopAfterSnapshot(t)
		const copies = 1024
		for range copies {
			duplicate := &windowRoundFrame{
				bytes: MessagePoolShareReadOnly(f.notice.bytes),
				ack:   f.notice.ack,
			}
			f.wire.heldFrames = append(f.wire.heldFrames, duplicate)
			f.wire.forward(duplicate, f.wire.senderIn)
		}
		pending := f.pendingCount()
		retained := f.sequence.resendQueue.Len()
		if pending > retained {
			t.Errorf("one real retained-owner withdrawal stored %d notices for %d owners; replay copies=%d minimum_number_bytes=%d",
				pending, retained, copies, 8*pending)
		}
		f.afterSnapshot.release()
		f.requireRepairAndFinish(t, "duplicate real notices")
	})
}

// Cancellation retires the stopped child, not its live Client or the sibling
// force-stream sequence. Late old-generation notices must not recreate owners.
func TestEvictionFeedbackCanceledOwnerLeavesSharedSiblingRunnable(t *testing.T) {
	assertMessagePoolOwnership(t)
	synctest.Test(t, func(t *testing.T) {
		f := newEvictionFeedbackFixture(t, false)
		f.stopAfterSnapshot(t)
		f.wire.forward(f.sack, f.wire.senderIn)
		oldNotice := &windowRoundFrame{
			bytes: MessagePoolShareReadOnly(f.notice.bytes),
			ack:   f.notice.ack,
		}
		f.wire.heldFrames = append(f.wire.heldFrames, oldNotice)
		f.wire.forward(f.notice, f.wire.senderIn)
		f.sequence.Cancel()
		f.afterSnapshot.release()
		<-f.ownerExited
		synctest.Wait()
		if f.sequence.ctx.Err() == nil || f.sequence.resendQueue.Len() != 0 ||
			f.wire.ackedCount != 1 {
			t.Fatal("canceled source retained live retry custody or reported success")
		}
		beforeLate := f.pendingCount()
		f.wire.forward(oldNotice, f.wire.senderIn)
		if f.pendingCount() != beforeLate {
			t.Fatal("late old-generation notice created additional canceled-owner metadata")
		}
		var siblingAcked atomic.Bool
		frame := RequireToFrameWithDefaultProtocolVersion(&protocol.SimpleMessage{Content: "synthetic sibling"})
		accepted, err := f.wire.sender.SendWithTimeoutDetailed(
			frame, f.wire.receiver.ClientId(), func(err error) {
				if err == nil {
					siblingAcked.Store(true)
				}
			}, time.Second, TransferKey{ForceStream: true})
		if !accepted || err != nil {
			MessagePoolReturn(frame.MessageBytes)
			t.Fatalf("healthy shared-client sibling refused: accepted=%t err=%v", accepted, err)
		}
		sibling := f.wire.take(f.wire.senderOut)
		if sibling.pack == nil || !sibling.pack.ForceStream ||
			bytes.Equal(sibling.pack.SequenceId, f.victim.pack.SequenceId) {
			t.Fatal("shared-client sibling did not use an independent exact sequence")
		}
		f.wire.forward(f.wire.receive(sibling), f.wire.senderIn)
		if !siblingAcked.Load() || f.wire.sender.Ctx().Err() != nil ||
			f.sequence.resendQueue.Len() != 0 || f.wire.ackedCount != 1 {
			t.Fatal("late old notice or child cancellation damaged live sibling ownership")
		}
	})
}

// Lifecycle control: OLD actually passed this exact cancellation ordering.
// Preserve that result, and require the new fixed marker state to reconcile
// independently of the payload pool. No old cleanup defect is claimed.
func TestEvictionFeedbackCanceledOwnerReleasesPendingMetadata(t *testing.T) {
	assertMessagePoolOwnership(t)
	synctest.Test(t, func(t *testing.T) {
		f := newEvictionFeedbackFixture(t, false)
		f.stopAfterSnapshot(t)
		f.wire.forward(f.sack, f.wire.senderIn)
		f.wire.forward(f.notice, f.wire.senderIn)
		if f.pendingCount() != 1 {
			t.Fatal("cancellation metadata witness did not retain one genuine notice")
		}
		f.sequence.Cancel()
		f.afterSnapshot.release()
		<-f.ownerExited
		synctest.Wait()
		state := pendingEvictionStateForTest(f.sequence)
		if len(state.numbers) != 0 || state.pending != 0 || state.inFlight != 0 || state.detached || state.backingBytes != 0 {
			t.Errorf("reachable canceled source retained fixed eviction markers: %+v", state)
		}
		if f.sequence.resendQueue.Len() != 0 || f.wire.ackedCount != 1 {
			t.Fatal("metadata-only retention witness also leaked payload custody or false success")
		}
	})
}
